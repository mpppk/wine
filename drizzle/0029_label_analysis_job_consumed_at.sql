-- Issue #462: 完了したエチケット解析ジョブの「受け取り済み」を記録する。
--
-- #461 でジョブ本体は入ったが、完了したジョブを UI がどう見せるかは未実装だった。
-- マイセラー一覧に「解析中N件 / 完了N件」を出す以上、**完了を一度受け取ったら
-- バッジから消す**手段が要る。これが無いと、成功したジョブの `succeeded` は終端で
-- 変わらないので、完了バッジが永久に出続ける（あるいは「直近N時間の完了」のような
-- 時間ベースの誤魔化しになり、受け取ったかどうかとは無関係に消えたり残ったりする）。
--
-- **`status` に受け取り済みを足さない**。ジョブの状態機械（queued → running →
-- succeeded | failed）は「推論がどうなったか」を表すもので、利用者がその結果を
-- 画面で受け取ったかどうかは別の軸。混ぜると `isTerminalLabelJobStatus` の意味が
-- 「終わった」と「もう見せなくてよい」の二重になり、ポーリングの停止条件が濁る。
--
-- nullable + デフォルト無しの列追加（既存行は NULL = 未受け取り）なので
-- expand-and-contract の対象ではない（0027 と同じ形）。既存列の NOT NULL 化・
-- DROP・RENAME は無い。旧コードはこの列を書かないので、「新スキーマ×旧コード」の
-- 窓でも NULL のまま動く（＝未受け取り扱いで、バッジが出ないだけ）。
--
-- 索引は張らない。バッジの走査は既存の (user_id, status) で候補を絞ってから
-- この列を見るだけで、未終端＋未受け取りの件数は同時実行上限（3）で頭打ちになる。
ALTER TABLE `label_analysis_job` ADD COLUMN `consumed_at` integer;

-- Issue #405: 一括登録の申告枚数(photoCount)が永続化されず、2段階目で検証できない。
--
-- 一括登録は「先に登録を確定 → 後から写真をアップロード」の2段階で、目撃記録は
-- photoIndex でバッチの写真配列を指す。登録時の zod は
-- `photoIndex < photoCount` を検証するが、**その photoCount はどこにも残らない**
-- ため、2段階目(saveImportBatchPhotos)は申告枚数を知り得ない。JSDoc が
-- 「枚数が合わなければ拒否する」と書いている検証を実装できていなかった。
--
-- この列に申告枚数を残して、2段階目で不一致を拒否できるようにする。
--
-- nullable + デフォルト無しの列追加(既存行は NULL で埋まる)なので
-- expand-and-contract の対象ではない(0022/0024/0026 と同じ形)。既存列の
-- NOT NULL 化・DROP・RENAME は無い。旧コードはこの列を書かないので、
-- 「新スキーマ×旧コード」の窓でも NULL のまま動く。**NULL は「申告枚数が
-- 分からない既存バッチ」を意味し、その場合の検証はスキップする**(遡って
-- 埋められる値ではない。目撃記録の最大 photoIndex から下限は導けるが、
-- それは申告枚数とは別物なので偽の不一致を作る)。
--
-- 索引は張らない。参照するのはバッチ1件を id で引いた後の比較だけ。
ALTER TABLE `import_batch` ADD COLUMN `photo_count` integer;

-- Issue #472: エチケット解析ジョブと「その結果で記録されたワイン」を結び付ける。
--
-- 解析中に記録フォームを保存してページを離れると、完了通知/バッジからの受け取り
-- (`/cellar/new?labelJob=<id>`)が**必ず新規作成モードで開く**ため、同じワインが
-- 2件登録されていた。ジョブ行に作成済みエントリへの参照が無く、「このジョブの結果は
-- もう記録済みか」を突き合わせる手段が構造上存在しなかったのが原因。
--
-- この列があると、受け取りを「新規登録」ではなく「そのワインを編集」に振り分けられる
-- (候補は既存の差分ダイアログで反映する)。
--
-- **`consumed_at` とは別の軸**。consumed_at は「利用者が結果を画面で見たか」で、
-- こちらは「その結果が既存エントリに宛てられているか」。受け取らずに離脱した回は
-- consumed_at が NULL のまま entry_id だけ入りうるし、逆に新規登録として受け取った回は
-- consumed_at だけが入る。混ぜると受け取り導線の分岐がどちらの意味でも読めてしまう。
--
-- nullable + デフォルト無しの列追加(既存行は NULL = 宛先なし)なので
-- expand-and-contract の対象ではない(0029 と同じ形)。既存列の NOT NULL 化・DROP・
-- RENAME は無い。旧コードはこの列を書かないので、「新スキーマ×旧コード」の窓でも
-- NULL のまま動く(= 従来どおり新規作成モードで開くだけ)。
--
-- ON DELETE set null にするのは、宛先のワインが削除された後もジョブ行を残すため。
-- 参照だけ外れれば受け取りは新規作成モードへ素直に戻る(残った結果を捨てずに済む)。
--
-- 索引は張らない。参照は常に「ジョブIDで1行引いてから entry_id を見る」向きで、
-- entry_id からジョブを逆引きする経路が無い。
ALTER TABLE `label_analysis_job` ADD COLUMN `entry_id` text REFERENCES `drunk_wine`(`id`) ON UPDATE no action ON DELETE set null;
